export const SITE_CONTENT_ICON_OPTIONS = Object.keys(ICON_MAP).sort();

export function resolveSiteIcon(name: string): IconType {
  return ICON_MAP[name] ?? FaStar;
}

/** Extract a stable icon key from a react-icons component (or pass-through string). */
export function iconKeyFromComponent(icon: unknown): string {
  if (typeof icon === "string" && icon.trim()) return icon.trim();
  if (icon && typeof icon === "object") {
    const rec = icon as { displayName?: string; name?: string };
    const key = rec.displayName || rec.name;
    if (key && ICON_MAP[key]) return key;
    if (key) return key;
  }
  if (typeof icon === "function") {
    const fn = icon as { displayName?: string; name?: string };
    const key = fn.displayName || fn.name;
    if (key && ICON_MAP[key]) return key;
    if (key) return key;
  }
  return "FaStar";
}
